"""Export the ingame chronicle, including an English no-JavaScript fallback.

Usage: python tools/export-wiki.py --project-dir /path/to/UnityProject
Only Python's standard library is needed. Does not build or publish anything.
"""
import argparse
import html
import json
from pathlib import Path

parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('--project-dir',type=Path,required=True)
args=parser.parse_args()
source=args.project_dir/'Assets/Resources/Localization'
target=Path(__file__).resolve().parents[1]/'jones'
entries=json.loads((source/'wiki.json').read_text(encoding='utf-8'))['entries']
languages={code:{r['key']:r['value'] for r in json.loads((source/f'{code}.json').read_text(encoding='utf-8'))['entries'] if r['key'].startswith(('wiki.','category.'))} for code in ('en','de','fr')}
assert len({e['id'] for e in entries})==len(entries)
assert all(languages['en'].keys()==lang.keys() for lang in languages.values())
data={'entries':[{'id':e['id'],'category':e['category']} for e in entries],'categories':list(dict.fromkeys(e['category'] for e in entries)),'languages':languages}
(target/'wiki-data.js').write_text('// Generated by tools/export-wiki.py. Edit the game localization sources.\nwindow.JONES_WIKI = '+json.dumps(data,ensure_ascii=False,indent=2)+';\n',encoding='utf-8')
esc=html.escape
cards=[]
for e in entries:
 d=languages['en'];field=lambda key:esc(d['wiki.'+e['id']+'.'+key]);id=esc(e['id'],quote=True)
 cards.append(f'<details class="entry" id="{id}"><summary><span class="category">{esc(d["category."+e["category"]])}</span><h2>{field("title")}</h2><span class="summary">{field("summary")}</span></summary><div class="details"><p>{field("details")}</p><a class="permalink" href="#{id}">Link to this entry</a></div></details>')
template=(Path(__file__).parent/'wiki-template.html').read_text(encoding='utf-8')
(target/'index.html').write_text(template.replace('<!-- GENERATED_ENTRIES -->','\n'.join(cards)).replace('<!-- ENTRY_COUNT -->',str(len(entries))),encoding='utf-8')
print(f'Exported {len(entries)} articles in {len(languages)} languages to {target}')
